"""Score every reference run that exists with the HybridSearch harness and write
results/reference/reference_runs.{json,md} (+ .meta.json). Gates from the spec
("Published reference numbers") are checked to 4 decimals.

    python -m hybridsearch.eval.reference
"""
from __future__ import annotations

import sys

from ..data.io import DATA, read_qrels, read_run
from .metrics import evaluate
from .results import write_result

R = DATA / "runs" / "reference"
MS_DEV = DATA / "raw/msmarco/qrels.dev.small.tsv"
DL19 = DATA / "raw/trec-dl/dl19.qrels"
DL20 = DATA / "raw/trec-dl/dl20.qrels"
SUB = DATA / "subset/1m"
TT = DATA / "subset/train_tune/qrels.tsv"
T50 = DATA / "subset/train50k/qrels.tsv"

DEV_M = ["RR@10", "nDCG@10", "R@100", "R@1000"]
DL_M = ["nDCG@10", "RR(rel=2)@10", "R(rel=2)@100", "R(rel=2)@1000"]

# (run file, qrels, metrics, corpus, gates {metric: published})
RUNS = [
    ("anserini-bm25-default.dev.trec", MS_DEV, DEV_M, "full 8.8M", {"RR@10": 0.1840, "R@1000": 0.8526}),
    ("anserini-bm25-default.dl19.trec", DL19, DL_M, "full 8.8M", {"nDCG@10": 0.5058}),
    ("anserini-bm25-default.dl20.trec", DL20, DL_M, "full 8.8M", {"nDCG@10": 0.4796}),
    ("anserini-bm25-default.train_tune.trec", TT, DEV_M, "full 8.8M", {}),
    ("bm25.train50k.trec", T50, DEV_M, "full 8.8M", {}),
    ("bm25.train50k.first10k.trec", DATA / "subset/train50k/qrels.first10k.tsv", DEV_M, "full 8.8M", {}),
    ("anserini-bm25-default-1m.dev.trec", SUB / "qrels.dev.tsv", DEV_M, "1M subset", {}),
    ("anserini-bm25-default-1m.dl19.trec", SUB / "qrels.dl19.tsv", DL_M, "1M subset", {}),
    ("anserini-bm25-default-1m.dl20.trec", SUB / "qrels.dl20.tsv", DL_M, "1M subset", {}),
    ("anserini-bm25-default-1m.train_tune.trec", TT, DEV_M, "1M subset", {}),
    ("dense-flat-1m.dev.trec", SUB / "qrels.dev.tsv", DEV_M, "1M subset", {}),
    ("dense-flat-1m.dl19.trec", SUB / "qrels.dl19.tsv", DL_M, "1M subset", {}),
    ("dense-flat-1m.dl20.trec", SUB / "qrels.dl20.tsv", DL_M, "1M subset", {}),
    ("dense-flat-1m.train_tune.trec", TT, DEV_M, "1M subset", {}),
] + [
    (f"dense-flat.beir-{ds}.test.trec", DATA / f"raw/beir/{ds}/qrels/test.trec", ["nDCG@10", "R@100"], f"BEIR {ds}", {})
    for ds in ("scifact", "nfcorpus", "fiqa")
]


def main() -> int:
    rows = []
    ok = True
    for name, qrels_path, metrics, corpus, gates in RUNS:
        p = R / name
        if not p.exists() or not qrels_path.exists():
            continue
        run, qrels = read_run(p), read_qrels(qrels_path)
        agg, _ = evaluate(run, qrels, metrics)
        gate_res = {}
        for m, want in gates.items():
            got = round(agg[m], 4)
            gate_res[m] = {"published": want, "ours": got, "pass": got == want}
            ok &= got == want
        rows.append({"run": f"data/runs/reference/{name}", "qrels": str(qrels_path.relative_to(DATA.parent)),
                     "corpus": corpus, "queries_in_qrels": len(qrels),
                     "queries_missing_from_run": sum(1 for q in qrels if q not in run),
                     "metrics": {k: round(v, 4) for k, v in agg.items()}, "gates": gate_res})
    md = ["# Reference runs scored by the HybridSearch harness", "",
          ("Generated by `python -m hybridsearch.eval.reference`. Metric conventions: py/hybridsearch/eval/metrics.py "
          "(trec_eval parity, tested). DL metrics RR/R use rel>=2 (Anserini's `-l 2`); nDCG uses graded gains."), "",
          "| run | corpus | #q | metrics | gate |", "|---|---|---|---|---|"]
    for r in rows:
        ms = ", ".join(f"{k} {v:.4f}" for k, v in r["metrics"].items())
        gs = "; ".join(f"{m}: {g['ours']:.4f} vs {g['published']:.4f} {'PASS' if g['pass'] else 'FAIL'}" for m, g in r["gates"].items())
        md.append(f"| `{r['run'].split('/')[-1]}` | {r['corpus']} | {r['queries_in_qrels']} | {ms} | {gs} |")
    write_result("reference/reference_runs.json", {"all_gates_pass": ok, "runs": rows}, command="python -m hybridsearch.eval.reference")
    write_result("reference/reference_runs.md", "\n".join(md) + "\n", command="python -m hybridsearch.eval.reference")
    print("\n".join(md))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
